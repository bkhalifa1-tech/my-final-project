package com.example.myfinalproject;

import java.util.ArrayList;

public class WeeklyPregnancyData{
    private WeeklyPregnancyData(){}

    public static ArrayList<String> getWeeklyTips(int week){
        ArrayList<String> tips=new ArrayList<>();

        tips.add("تطور الجنين: "+getDevelopment(week));
        tips.add("نصيحة غذائية: "+getNutritionTip(week));
        tips.add("نصيحة صحية: "+getHealthTip(week));
        tips.add("تنبيه مهم: "+getWarningTip(week));

        return tips;
    }

    public static String getDevelopment(int week){
        switch(week){
            case 1:return "يبدأ حساب الحمل من أول يوم في آخر دورة شهرية.";
            case 2:return "يستعد الجسم لحدوث الإباضة والتخصيب.";
            case 3:return "قد يحدث التخصيب وتبدأ البويضة بالانقسام.";
            case 4:return "تبدأ البويضة المخصبة بالانغراس في جدار الرحم.";
            case 5:return "يبدأ تكوّن القلب والجهاز العصبي المبكر.";
            case 6:return "يبدأ قلب الجنين بالنبض وتظهر براعم الأطراف.";
            case 7:return "ينمو الدماغ بسرعة وتبدأ ملامح الوجه بالظهور.";
            case 8:return "تتكون بدايات الأصابع والأنف والأذنين.";
            case 9:return "تتطور الأعضاء الداخلية وتزداد حركة الجنين.";
            case 10:return "تكون معظم الأعضاء الأساسية قد بدأت بالتشكل.";
            case 11:return "تبدأ الأظافر وبصيلات الشعر بالتكوّن.";
            case 12:return "تصبح ملامح الوجه أكثر وضوحًا.";
            case 13:return "يبدأ الثلث الثاني ويزداد نمو جسم الجنين.";
            case 14:return "يمكن للجنين تحريك عضلات وجهه.";
            case 15:return "تبدأ العظام بالتصلب ويزداد طول الأطراف.";
            case 16:return "قد تبدأ الأم بالشعور بحركة خفيفة للجنين.";
            case 17:return "يبدأ تكوّن طبقة الدهون تحت الجلد.";
            case 18:return "تتطور حاسة السمع وقد يسمع الجنين الأصوات.";
            case 19:return "تغطي جسم الجنين طبقة واقية.";
            case 20:return "وصل الحمل إلى منتصف مدته تقريبًا.";
            case 21:return "تزداد حركة الجنين ويستطيع البلع.";
            case 22:return "تظهر الحواجب والرموش بشكل أوضح.";
            case 23:return "تتطور الرئتان والأوعية الدموية داخلهما.";
            case 24:return "تزداد استجابة الجنين للأصوات والحركة.";
            case 25:return "تزداد دقة حركات اليدين والأصابع.";
            case 26:return "تبدأ العينان بالانفتاح تدريجيًا.";
            case 27:return "يقترب الثلث الثاني من الاكتمال.";
            case 28:return "يبدأ الثلث الثالث وينمو الدماغ بسرعة.";
            case 29:return "تزداد قوة العضلات ويزداد وزن الجنين.";
            case 30:return "يبدأ نخاع العظم بإنتاج خلايا الدم.";
            case 31:return "تستمر الرئتان والجهاز العصبي في النضج.";
            case 32:return "يصبح جلد الجنين أكثر نعومة.";
            case 33:return "تزداد صلابة العظام مع بقاء الجمجمة مرنة.";
            case 34:return "تستمر الرئتان بالنضج استعدادًا للولادة.";
            case 35:return "تكون معظم أعضاء الجسم قد اكتملت تقريبًا.";
            case 36:return "قد يبدأ الجنين بالنزول إلى منطقة الحوض.";
            case 37:return "يعتبر الحمل قريبًا من الاكتمال.";
            case 38:return "تزداد الدهون التي تساعد على تنظيم حرارة الجسم.";
            case 39:return "تكون أعضاء الجنين جاهزة للعمل خارج الرحم.";
            case 40:return "وصل الحمل إلى موعد الولادة المتوقع.";
            default:return "لا توجد معلومات متاحة لهذا الأسبوع.";
        }
    }

    private static String getNutritionTip(int week){
        if(week<=4)return "ابدئي بتناول حمض الفوليك بعد استشارة الطبيب.";
        if(week<=8)return "تناولي مصادر الحديد مثل العدس والخضروات الورقية.";
        if(week<=12)return "قسمي طعامك إلى وجبات صغيرة لتخفيف الغثيان.";
        if(week<=16)return "اهتمي بالكالسيوم والحليب ومشتقاته المناسبة.";
        if(week<=20)return "تناولي البروتين من اللحوم المطهية والبيض والبقوليات.";
        if(week<=24)return "اشربي الماء وتناولي الألياف لتقليل الإمساك.";
        if(week<=28)return "قللي الأطعمة المالحة والمصنعة.";
        if(week<=32)return "تناولي وجبات صغيرة غنية بالبروتين والحديد.";
        if(week<=36)return "اختاري وجبات خفيفة وسهلة الهضم.";
        return "حافظي على غذاء متوازن واشربي كمية كافية من الماء.";
    }

    private static String getHealthTip(int week){
        if(week<=4)return "تجنبي التدخين والكحول والأدوية دون استشارة الطبيب.";
        if(week<=8)return "احصلي على الراحة والنوم الكافي.";
        if(week<=12)return "راجعي الطبيب عند القيء المستمر أو فقدان السوائل.";
        if(week<=16)return "مارسي المشي الخفيف إذا سمح الطبيب.";
        if(week<=20)return "التزمي بمواعيد الفحوصات الدورية.";
        if(week<=24)return "ابدئي بملاحظة حركة الجنين تدريجيًا.";
        if(week<=28)return "راقبي ضغط الدم والتورم والصداع.";
        if(week<=32)return "نامي على الجانب الأيسر قدر الإمكان.";
        if(week<=36)return "ابدئي بتجهة حقيبة المستشفى.";
        return "احصلي على الراحة وراقبي علامات بدء الولادة.";
    }

    private static String getWarningTip(int week){
        if(week<=12)return "راجعي الطبيب عند وجود نزيف أو ألم شديد أو دوخة مستمرة.";
        if(week<=20)return "راجعي الطبيب عند الشعور بألم قوي أو خروج سوائل غير طبيعية.";
        if(week<=28)return "راجعي الطبيب عند قلة حركة الجنين أو الصداع الشديد.";
        if(week<=36)return "انتبهي للتورم المفاجئ أو ارتفاع الضغط أو تقلصات منتظمة.";
        return "توجهي للمستشفى عند نزول ماء الجنين أو بدء تقلصات منتظمة.";
    }
}
