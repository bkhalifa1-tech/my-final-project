    public static String formatDate(int year,int month,int day){
        return String.format(Locale.US,"%04d-%02d-%02d",year,month+1,day);
    }

    public static Calendar dateToCalendar(String date){
        if(date==null||date.trim().isEmpty())return null;
        String[] parts=date.split("-");
        if(parts.length!=3)return null;
        int year=Integer.parseInt(parts[0]);
        int month=Integer.parseInt(parts[1])-1;
        int day=Integer.parseInt(parts[2]);
        Calendar calendar=Calendar.getInstance();
        calendar.set(year,month,day,0,0,0);
        calendar.set(Calendar.MILLISECOND,0);
        return calendar;
    }

    public static String calculateDueDate(String lastPeriodDate){
        Calendar calendar=dateToCalendar(lastPeriodDate);
        if(calendar==null)return "";
        calendar.add(Calendar.DAY_OF_YEAR,280);
        return new SimpleDateFormat("yyyy-MM-dd",Locale.US).format(calendar.getTime());
    }

    public static int calculateWeek(String lastPeriodDate){
        Calendar lastPeriod=dateToCalendar(lastPeriodDate);
        if(lastPeriod==null)return 0;
        long difference=System.currentTimeMillis()-lastPeriod.getTimeInMillis();
        int days=(int)(difference/86400000L);
        if(days<0)return 0;
        int week=(days/7)+1;
        if(week>40)week=40;
        return week;
    }

    public static int calculateMonth(int week) {
        if (week <= 4) return 1;
        if (week <= 8) return 2;
        if (week <= 13) return 3;
        if (week <= 17) return 4;
        if (week <= 22) return 5;
        if (week <= 27) return 6;
        if (week <= 31) return 7;
        if (week <= 35) return 8;
        return 9;
    }

